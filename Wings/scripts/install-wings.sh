#!/usr/bin/env bash
# SiliconHost Wings installer
# Installs the Wings compute-node daemon on a VPS and connects it to a panel node.
set -euo pipefail

WINGS_DIR="${WINGS_DIR:-/opt/siliconhost-wings}"
SERVICE_NAME="wings"
LOG_DIR="/var/log/wings"

PANEL_URL="${PANEL_URL:-}"
NODE_ID="${NODE_ID:-}"
NODE_TOKEN="${API_KEY:-${NODE_TOKEN:-}}"
NODE_NAME="${NODE_NAME:-}"
VPS_IP="${VPS_IP:-}"
SSH_USER="${SSH_USER:-root}"
SSH_PORT="${SSH_PORT:-22}"
SSH_PASSWORD="${SSH_PASSWORD:-}"
SOURCE_DIR="${SOURCE_DIR:-}"
NON_INTERACTIVE=0
SKIP_DEPS=0

log_info() { printf '\033[1;34m[INFO]\033[0m %b\n' "$*"; }
log_ok()   { printf '\033[1;32m[OK]\033[0m %b\n' "$*"; }
log_warn() { printf '\033[1;33m[WARN]\033[0m %b\n' "$*"; }
log_err()  { printf '\033[1;31m[ERR]\033[0m %b\n' "$*" >&2; }

usage() {
  cat <<'EOF'
Usage: sudo bash install-wings.sh [options]

Options:
  --panel-url <url>       Panel base URL, e.g. http://203.0.113.10:3001
  --node-id <id>          Node ID from the panel (Nodes -> Create Node)
  --token <token>         Node token shown in the panel configuration tab
  --name <name>           Node name to report to the panel
  --ip <address>          Public IP of this Wings VPS
  --ssh-user <user>       SSH username the panel uses to manage this VPS (default: root)
  --ssh-port <port>       SSH port (default: 22)
  --ssh-password <pass>   SSH password the panel uses to manage this VPS
  --source <dir>          Wings source directory (default: this script's parent folder)
  --skip-deps             Do not install/upgrade system packages
  -y, --non-interactive   Fail instead of prompting for missing values
  -h, --help              Show this help

You can also paste the configuration script generated by the panel while
Wings is already installed; that only rewrites wings.yml and restarts the service.
EOF
}

require_root() {
  if [ "$(id -u)" -ne 0 ]; then
    log_err "This script must be run as root. Use: sudo bash $0"
    exit 1
  fi
}

yaml_quote() {
  local value="${1//\\/\\\\}"
  value="${value//\"/\\\"}"
  printf '"%s"' "$value"
}

detect_ip() {
  curl -fsS -4 --max-time 5 https://api.ipify.org 2>/dev/null \
    || curl -fsS -4 --max-time 5 https://ifconfig.me 2>/dev/null \
    || ip route get 1.1.1.1 2>/dev/null | awk '{for (i = 1; i <= NF; i++) if ($i == "src") { print $(i + 1); exit }}' \
    || hostname -I 2>/dev/null | awk '{print $1}' \
    || echo ""
}

node_major() {
  if ! command -v node >/dev/null 2>&1; then echo 0; return; fi
  node -v | sed 's/^v//; s/\..*$//'
}

install_dependencies() {
  [ "$SKIP_DEPS" -eq 1 ] && return 0

  if [ "$(node_major)" -ge 20 ] \
    && command -v qemu-system-x86_64 >/dev/null 2>&1 \
    && command -v qemu-img >/dev/null 2>&1 \
    && command -v cloud-localds >/dev/null 2>&1 \
    && command -v wget >/dev/null 2>&1; then
    log_ok "All required packages are already installed"
    return 0
  fi

  if ! command -v apt-get >/dev/null 2>&1; then
    log_warn "This installer supports Debian/Ubuntu. Install node >= 20, qemu-system-x86, qemu-utils and cloud-image-utils manually."
    return 0
  fi

  log_info "Installing hypervisor and helper packages..."
  log_info "This downloads a few hundred MB and can take several minutes on a slow link."
  export DEBIAN_FRONTEND=noninteractive
  # Never stop on a conffile prompt or a lock held by unattended-upgrades.
  local -a apt_opts=(
    -y
    -o DPkg::Lock::Timeout=900
    -o Dpkg::Options::=--force-confdef
    -o Dpkg::Options::=--force-confold
    -o Acquire::Retries=5
  )
  apt-get "${apt_opts[@]}" update
  apt-get "${apt_opts[@]}" install --no-install-recommends \
    curl wget ca-certificates git tar xz-utils \
    qemu-system-x86 qemu-utils cloud-image-utils iproute2

  if [ "$(node_major)" -lt 20 ]; then
    log_info "Installing Node.js 20 LTS..."
    curl -fsSL https://deb.nodesource.com/setup_20.x | bash -
    apt-get "${apt_opts[@]}" install nodejs
  fi

  log_ok "Dependencies ready (node $(node -v), $(qemu-system-x86_64 --version 2>/dev/null | head -n1 || echo 'QEMU missing'))"
}

prompt_values() {
  if [ "$NON_INTERACTIVE" -eq 1 ]; then
    local missing=()
    [ -z "$PANEL_URL" ] && missing+=("--panel-url")
    [ -z "$NODE_ID" ] && missing+=("--node-id")
    [ -z "$NODE_TOKEN" ] && missing+=("--token")
    if [ "${#missing[@]}" -gt 0 ]; then
      log_err "Missing required options: ${missing[*]}"
      exit 1
    fi
    return 0
  fi

  echo ""
  log_info "=== Wings node connection details ==="
  log_info "Find these in the panel: Admin -> Nodes -> your node -> Configuration."
  echo ""

  while [ -z "$PANEL_URL" ]; do
    read -r -p "Panel URL (e.g. http://1.2.3.4:3001): " PANEL_URL
  done
  while [ -z "$NODE_ID" ]; do
    read -r -p "Node ID (number shown in the panel): " NODE_ID
  done
  while [ -z "$NODE_TOKEN" ]; do
    read -r -p "Node token (from the panel configuration script): " NODE_TOKEN
  done

  if [ -z "$NODE_NAME" ]; then
    read -r -p "Node name [Wings Node ${NODE_ID}]: " NODE_NAME
    NODE_NAME="${NODE_NAME:-Wings Node ${NODE_ID}}"
  fi

  if [ -z "$VPS_IP" ]; then
    local detected
    detected="$(detect_ip)"
    read -r -p "Public IP of this Wings VPS [${detected}]: " VPS_IP
    VPS_IP="${VPS_IP:-$detected}"
  fi

  echo ""
  log_info "=== Panel SSH access to this VPS ==="
  log_info "The panel uses these to start/stop Wings and read its logs."
  read -r -p "SSH username [${SSH_USER}]: " input_user
  SSH_USER="${input_user:-$SSH_USER}"
  read -r -p "SSH port [${SSH_PORT}]: " input_port
  SSH_PORT="${input_port:-$SSH_PORT}"
  if [ -z "$SSH_PASSWORD" ]; then
    read -r -s -p "SSH password (leave blank to skip SSH control): " SSH_PASSWORD
    echo ""
  fi
}

validate_values() {
  case "$PANEL_URL" in
    http://*|https://*) ;;
    *) log_err "Panel URL must start with http:// or https://"; exit 1 ;;
  esac
  [[ "$NODE_ID" =~ ^[0-9]+$ ]] || { log_err "Node ID must be a number"; exit 1; }
  [ -n "$NODE_TOKEN" ] || { log_err "Node token cannot be empty"; exit 1; }
  [[ "$SSH_PORT" =~ ^[0-9]+$ ]] || { log_err "SSH port must be a number"; exit 1; }
  PANEL_URL="${PANEL_URL%/}"
  NODE_NAME="${NODE_NAME:-Wings Node ${NODE_ID}}"
}

copy_source() {
  local src="${SOURCE_DIR:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
  if [ ! -f "$src/src/index.js" ]; then
    log_err "Wings source not found at $src (expected src/index.js)."
    log_err "Copy the panel repository's Wings folder here and pass --source <path>."
    exit 1
  fi

  mkdir -p "$WINGS_DIR"
  if [ "$(cd "$src" && pwd)" != "$(cd "$WINGS_DIR" && pwd)" ]; then
    log_info "Installing Wings files into $WINGS_DIR..."
    mkdir -p "$WINGS_DIR/config"
    cp -a "$src/src" "$src/scripts" "$src/systemd" "$src/package.json" "$WINGS_DIR/"
    [ -f "$src/config/wings.yml.example" ] && cp -a "$src/config/wings.yml.example" "$WINGS_DIR/config/"
  fi
}

install_node_modules() {
  log_info "Installing Node.js dependencies..."
  ( cd "$WINGS_DIR" && npm install --omit=dev --no-audit --no-fund >/tmp/wings-npm-install.log 2>&1 ) || {
    log_err "npm install failed. See /tmp/wings-npm-install.log"
    tail -n 30 /tmp/wings-npm-install.log >&2 || true
    exit 1
  }
  log_ok "Node.js dependencies installed"
}

write_config() {
  log_info "Writing Wings configuration..."
  mkdir -p "$WINGS_DIR/config" "$LOG_DIR" /var/lib/wings/vms /var/lib/wings/images

  umask 077
  cat > "$WINGS_DIR/config/wings.yml" <<EOF
panel:
  url: $(yaml_quote "$PANEL_URL")
  api_key: $(yaml_quote "$NODE_TOKEN")

node:
  id: $NODE_ID
  name: $(yaml_quote "$NODE_NAME")

vps:
  ip: $(yaml_quote "$VPS_IP")
  ssh_user: $(yaml_quote "$SSH_USER")
  ssh_port: $SSH_PORT
  ssh_password: $(yaml_quote "$SSH_PASSWORD")

storage:
  vm_dir: "/var/lib/wings/vms"
  images_dir: "/var/lib/wings/images"

ssh:
  port: 22
  user: "root"
  key_path: "/root/.ssh/id_rsa"

logging:
  level: "info"
  file: "/var/log/wings/wings.log"
EOF

  cat > "$WINGS_DIR/config/.env" <<EOF
WINGS_CONFIG=$WINGS_DIR/config/wings.yml
WINGS_LOG_FILE=$LOG_DIR/wings.log
NODE_ENV=production
EOF
  chmod 600 "$WINGS_DIR/config/wings.yml" "$WINGS_DIR/config/.env"
  umask 022
  log_ok "Configuration written to $WINGS_DIR/config/wings.yml"
}

install_service() {
  local node_bin
  node_bin="$(command -v node)"
  [ -n "$node_bin" ] || { log_err "Node.js executable not found"; exit 1; }

  log_info "Installing systemd service..."
  cp "$WINGS_DIR/systemd/wings.service" /etc/systemd/system/wings.service
  sed -i "s|^ExecStart=.*|ExecStart=${node_bin} src/index.js|" /etc/systemd/system/wings.service
  systemctl daemon-reload
  systemctl enable "$SERVICE_NAME" >/dev/null
  systemctl restart "$SERVICE_NAME"

  log_info "Waiting for Wings to connect..."
  sleep 3
  if systemctl is-active --quiet "$SERVICE_NAME"; then
    log_ok "Wings service is running"
  else
    log_err "Wings failed to start. Recent logs:"
    journalctl -u "$SERVICE_NAME" -n 40 --no-pager || true
    exit 1
  fi
}

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --panel-url) PANEL_URL="${2:-}"; shift 2 ;;
      --node-id) NODE_ID="${2:-}"; shift 2 ;;
      --token|--api-key) NODE_TOKEN="${2:-}"; shift 2 ;;
      --name) NODE_NAME="${2:-}"; shift 2 ;;
      --ip) VPS_IP="${2:-}"; shift 2 ;;
      --ssh-user) SSH_USER="${2:-}"; shift 2 ;;
      --ssh-port) SSH_PORT="${2:-}"; shift 2 ;;
      --ssh-password) SSH_PASSWORD="${2:-}"; shift 2 ;;
      --source) SOURCE_DIR="${2:-}"; shift 2 ;;
      --skip-deps) SKIP_DEPS=1; shift ;;
      -y|--yes|--non-interactive) NON_INTERACTIVE=1; shift ;;
      -h|--help) usage; exit 0 ;;
      *) log_warn "Unknown option: $1"; shift ;;
    esac
  done
}

main() {
  parse_args "$@"
  require_root

  log_info "=== SiliconHost Wings Installer ==="
  prompt_values
  validate_values
  [ -z "$VPS_IP" ] && VPS_IP="$(detect_ip)"

  install_dependencies
  copy_source
  install_node_modules
  write_config
  install_service

  echo ""
  log_ok "=== Wings installation complete ==="
  echo "  Panel:      $PANEL_URL"
  echo "  Node:       $NODE_ID ($NODE_NAME)"
  echo "  VM storage: /var/lib/wings/vms"
  echo ""
  echo "Verify with:  systemctl status wings"
  echo "View logs:    journalctl -u wings -f"
  echo "The panel Nodes page should now show this node as Wings Online."
}

main "$@"
